#!/bin/sh
set -eu
psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set=ON_ERROR_STOP=1 --set=owner_password="$MIGRATION_DB_PASSWORD" --set=app_password="$APP_DB_PASSWORD" <<'SQL'
CREATE ROLE helpdesk_owner LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD :'owner_password';
CREATE ROLE helpdesk_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD :'app_password';
ALTER DATABASE helpdesk OWNER TO helpdesk_owner;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO helpdesk_owner;
GRANT USAGE ON SCHEMA public TO helpdesk_app;
ALTER DEFAULT PRIVILEGES FOR ROLE helpdesk_owner IN SCHEMA public GRANT SELECT,INSERT,UPDATE,DELETE ON TABLES TO helpdesk_app;
ALTER DEFAULT PRIVILEGES FOR ROLE helpdesk_owner IN SCHEMA public GRANT USAGE,SELECT ON SEQUENCES TO helpdesk_app;
SQL
